export function CategoryIcon({ category, size = 20 }: { category: string; size?: number }) {
  switch (category) {
    case 'image':
      return <ImageIcon size={size} color="#38bdf8" />;
    case 'video':
      return <VideoIcon size={size} color="#a855f7" />;
    case 'audio':
      return <AudioIcon size={size} color="#ec4899" />;
    case 'document':
      return <DocumentIcon size={size} color="#3b82f6" />;
    case 'code':
      return <CodeIcon size={size} color="#10b981" />;
    case 'archive':
      return <ArchiveIcon size={size} color="#f59e0b" />;
    case 'folder':
      return <FolderIcon size={size} color="#60a5fa" />;
    default:
      return <FileIcon size={size} color="#94a3b8" />;
  }
}
